export async function openDispute(txId: string, reason: DisputeReason, description: string) {
  const tx = await db.transactions.get(txId);
  if (!tx) throw new BankError('NOT_FOUND', { object: 'transaction' });
  const a = actor();
  if (!tx.partyIds.includes(a.userId)) throw new BankError('PERMISSION_DENIED');
  if (tx.status !== 'completed') throw new BankError('INVALID_STATE', { status: tx.status });
  const open = await db.disputes.where('txId').equals(txId).filter((d) => !['resolved', 'rejected', 'refunded'].includes(d.status)).count();
  if (open) throw new BankError('INVALID_STATE', { reason: 'dispute already open' });
  const d: Dispute = {
    id: uid('DSP'), number: `DS-${randomDigits(7)}`, ownerId: a.userId, txId, reason, description, amount: tx.amount + tx.fee, currency: tx.currency,
    status: 'opened', createdAt: nowISO(), updatedAt: nowISO(), timeline: [{ status: 'opened', at: nowISO(), by: a.name }], evidence: [],
  };
  await db.disputes.add(d);
  await audit({ action: 'dispute.open', object: 'dispute', objectId: d.id, txId, details: reason });
  await notify(a.userId, { category: 'payments', titleKey: 'n.dispute.opened.title', bodyKey: 'n.dispute.opened.body', params: { number: d.number, ref: tx.ref }, link: `/disputes/${d.id}` });
  return d;
}

export async function addDisputeEvidence(id: string, text: string) {
  const d = await db.disputes.get(id);
  if (!d) throw new BankError('NOT_FOUND');
  const a = actor();
  if (d.ownerId !== a.userId && !can('disputes.review')) throw new BankError('PERMISSION_DENIED');
  if (!text.trim()) throw new BankError('VALIDATION', { field: 'evidence' });
  const status: DisputeStatus = d.status === 'evidence_required' && d.ownerId === a.userId ? 'under_review' : d.status;
  await db.disputes.update(id, {
    evidence: [...d.evidence, { at: nowISO(), by: a.name, text }], status, updatedAt: nowISO(),
    timeline: status !== d.status ? [...d.timeline, { status, at: nowISO(), by: a.name, note: 'evidence submitted' }] : d.timeline,
  });
  await audit({ action: 'dispute.evidence', object: 'dispute', objectId: id });
}

export async function setDisputeStatus(id: string, status: DisputeStatus, note = '') {
  requirePermission('disputes.review');
  const d = await db.disputes.get(id);
  if (!d) throw new BankError('NOT_FOUND');
  if (['resolved', 'rejected', 'refunded'].includes(d.status)) throw new BankError('INVALID_STATE', { status: d.status });
  let refundTxId: string | undefined;
  if (status === 'refunded') {
    const tx = await db.transactions.get(d.txId);
    if (!tx) throw new BankError('NOT_FOUND');
    const target = tx.fromAccountId ?? tx.toAccountId;
    if (!target) throw new BankError('INVALID_ACCOUNT');
    const acc = await getAccountOrThrow(target);
    const ccy = acc.pockets.includes(d.currency) ? d.currency : acc.currency;
    const refund = await execute({
      draft: {
        type: 'refund', amount: d.amount, currency: ccy, toAccountId: acc.id, sender: { name: 'Disputes & Chargebacks' }, recipient: { name: acc.name, accountNumber: acc.number },
        description: `Refund for dispute ${d.number} (${tx.ref})`, category: 'transfers', channel: 'system', refPrefix: 'RFD', relatedTxIds: [tx.id], partyIds: [d.ownerId],
      },
      screen: false,
      plan: () => [{ memo: `Dispute refund ${d.number}`, allowOverdraft: true, lines: [{ accountId: GL.DISPUTES, currency: ccy, side: 'D', amount: d.amount }, { accountId: acc.id, currency: ccy, side: 'C', amount: d.amount }] }],
    });
    refundTxId = refund.id;
    await db.transactions.update(tx.id, { relatedTxIds: [...tx.relatedTxIds, refund.id] });
  }
  await db.disputes.update(id, { status, refundTxId, updatedAt: nowISO(), timeline: [...d.timeline, { status, at: nowISO(), by: actor().name, note }] });
  await audit({ action: `dispute.${status}`, object: 'dispute', objectId: id, txId: refundTxId, details: note });
  await notify(d.ownerId, { category: 'payments', titleKey: 'n.dispute.update.title', bodyKey: 'n.dispute.update.body', params: { number: d.number, status }, link: `/disputes/${id}`, priority: status === 'evidence_required' ? 'high' : 'normal' });
  await sendMail(d.ownerId, 'dispute_update', { number: d.number, status, note });
}

