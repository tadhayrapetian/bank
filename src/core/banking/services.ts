export async function buyPolicy(product: InsuranceProduct, period: 'monthly' | 'yearly', accountId: string, insured: string) {
  const acc = await getAccountOrThrow(accountId);
  if (!canOperate(acc)) throw new BankError('PERMISSION_DENIED');
  if (acc.currency !== 'CRWN' && !acc.pockets.includes('CRWN')) throw new BankError('CURRENCY_UNSUPPORTED', { currency: acc.currency, required: 'CRWN' });
  const def = INSURANCE_PRODUCTS[product];
  const start = todayKey();
  const p: InsurancePolicy = {
    id: uid('POLY'), number: `WM-${product.slice(0, 2).toUpperCase()}-${randomDigits(6)}`, ownerId: acc.ownerId, product, insured: insured || product,
    coverage: def.coverage, premium: period === 'monthly' ? def.premiumMonthly : def.premiumYearly, currency: 'CRWN', period,
    startDate: start, endDate: addYears(start, 1).toISOString().slice(0, 10),
    nextPremium: (period === 'monthly' ? addMonths(start, 1) : addYears(start, 1)).toISOString().slice(0, 10),
    status: 'active', accountId: acc.id, createdAt: nowISO(),
  };
  await chargePremium(p);
  const owner = await db.users.get(acc.ownerId);
  const doc = await createDocument({
    type: 'policy', title: 'Insurance Policy', ownerId: acc.ownerId,
    data: { policyId: p.id, number: p.number, product, insured: p.insured, coverage: p.coverage, premium: p.premium, currency: p.currency, period, startDate: p.startDate, endDate: p.endDate, holder: owner?.name, insurer: 'Wardstone Mutual (demonstration product)' },
    authorName: 'Wardstone Mutual', authorId: 'BANK', expiresAt: p.endDate + 'T23:59:59.000Z',
  });
  p.documentId = doc.id;
  await db.policies.add(p);
  await audit({ action: 'insurance.buy', object: 'policy', objectId: p.id, details: `${product} ${period}` });
  await sendMail(acc.ownerId, 'policy_issued', { number: p.number, product }, doc.id);
  return p;
}

export async function payPremium(id: string) {
  const p = await db.policies.get(id);
  if (!p) throw new BankError('NOT_FOUND');
  if (p.ownerId !== actor().userId && !actor().system) throw new BankError('PERMISSION_DENIED');
  if (!['active', 'lapsed'].includes(p.status)) throw new BankError('INVALID_STATE', { status: p.status });
  const tx = await chargePremium(p);
  const next = (p.period === 'monthly' ? addMonths(p.nextPremium, 1) : addYears(p.nextPremium, 1)).toISOString().slice(0, 10);
  await db.policies.update(id, { nextPremium: next, status: 'active' });
  return tx;
}

