export async function decideClaim(id: string, decision: 'under_review' | 'approved' | 'denied' | 'paid') {
  requirePermission('claims.review');
  const c = await db.claims.get(id);
  if (!c) throw new BankError('NOT_FOUND');
  const p = await db.policies.get(c.policyId);
  if (!p) throw new BankError('NOT_FOUND');
  let payoutTxId: string | undefined;
  if (decision === 'paid') {
    if (c.status !== 'approved') throw new BankError('INVALID_STATE', { status: c.status });
    const acc = await getAccountOrThrow(p.accountId);
    const tx = await execute({
      draft: { type: 'claim', amount: c.amount, currency: c.currency, toAccountId: acc.id, sender: { name: 'Wardstone Mutual' }, recipient: { name: acc.name, accountNumber: acc.number }, description: `Claim payout ${c.number}`, category: 'insurance', channel: 'system', refPrefix: 'INS', partyIds: [c.ownerId] },
      screen: false,
      plan: () => [{ memo: `Claim ${c.number}`, allowOverdraft: true, lines: [{ accountId: GL.INSURANCE, currency: c.currency, side: 'D', amount: c.amount }, { accountId: acc.id, currency: c.currency, side: 'C', amount: c.amount }] }],
    });
    payoutTxId = tx.id;
  }
  await db.claims.update(id, { status: decision, payoutTxId, timeline: [...c.timeline, { step: decision === 'denied' ? 'rejected' : decision === 'paid' ? 'completed' : decision === 'approved' ? 'approved' : 'review', at: nowISO(), ok: decision !== 'denied', actor: actor().name }] });
  await audit({ action: `insurance.claim_${decision}`, object: 'claim', objectId: id, txId: payoutTxId });
  await notify(c.ownerId, { category: 'system', titleKey: 'n.claim.update.title', bodyKey: 'n.claim.update.body', params: { number: c.number, status: decision }, link: '/insurance' });
  await sendMail(c.ownerId, 'claim_update', { number: c.number, status: decision });
}

export async function processPolicies(dayKey: string) {
  const active = await db.policies.where('status').equals('active').toArray();
  for (const p of active) {
    if (p.endDate < dayKey) {
      await db.policies.update(p.id, { status: 'expired' });
      continue;
    }
    if (p.nextPremium <= dayKey) {
      try {
        await chargePremium(p);
        const next = (p.period === 'monthly' ? addMonths(p.nextPremium, 1) : addYears(p.nextPremium, 1)).toISOString().slice(0, 10);
        await db.policies.update(p.id, { nextPremium: next });
      } catch {
        await db.policies.update(p.id, { status: 'lapsed' });
        await notify(p.ownerId, { category: 'system', titleKey: 'n.policy.lapsed.title', bodyKey: 'n.policy.lapsed.body', params: { number: p.number }, link: '/insurance', priority: 'high' });
      }
    }
  }
}

