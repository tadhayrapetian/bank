export async function submitKyc(input: { docType: KycDocType; docNumber: string; issuedBy: string; issueDate: string; expiryDate: string; fileName?: string; fileData?: string }) {
  const a = actor();
  if (!input.docNumber.trim()) throw new BankError('VALIDATION', { field: 'docNumber' });
  if (input.expiryDate <= todayKey()) throw new BankError('DOCUMENT_EXPIRED');
  const rec: KycRecord = { id: uid('KYC'), userId: a.userId, ...input, docNumber: input.docNumber.trim().toUpperCase(), status: 'pending', submittedAt: nowISO() };
  await db.kyc.add(rec);
  const user = await db.users.get(a.userId);
  if (user && user.kycStatus !== 'verified') await db.users.update(a.userId, { kycStatus: 'pending' });
  await audit({ action: 'kyc.submit', object: 'kyc', objectId: rec.id, details: input.docType });
  return rec;
}

export async function reviewKyc(id: string, approve: boolean, reason = '') {
  requirePermission('kyc.review');
  const rec = await db.kyc.get(id);
  if (!rec) throw new BankError('NOT_FOUND');
  if (rec.status !== 'pending') throw new BankError('INVALID_STATE', { status: rec.status });
  await db.kyc.update(id, { status: approve ? 'verified' : 'rejected', reviewedAt: nowISO(), reviewedBy: actor().name, reason });
  const all = await db.kyc.where('userId').equals(rec.userId).toArray();
  const userStatus = all.some((k) => (k.id === id ? approve : k.status === 'verified')) ? 'verified' : approve ? 'verified' : all.some((k) => k.status === 'pending' && k.id !== id) ? 'pending' : 'rejected';
  await db.users.update(rec.userId, { kycStatus: userStatus });
  await audit({ action: approve ? 'kyc.verify' : 'kyc.reject', object: 'kyc', objectId: id, details: reason });
  await notify(rec.userId, { category: 'security', titleKey: approve ? 'n.kyc.verified.title' : 'n.kyc.rejected.title', bodyKey: approve ? 'n.kyc.verified.body' : 'n.kyc.rejected.body', params: { reason }, link: '/kyc', priority: 'high' });
  await sendMail(rec.userId, approve ? 'kyc_verified' : 'kyc_rejected', { reason });
}

export async function expireKyc(dayKey: string) {
  const verified = (await db.kyc.where('status').equals('verified').toArray()).filter((k) => k.expiryDate < dayKey);
  for (const k of verified) {
    await db.kyc.update(k.id, { status: 'expired' });
    const others = await db.kyc.where('userId').equals(k.userId).filter((x) => x.id !== k.id && x.status === 'verified').count();
    if (!others) await db.users.update(k.userId, { kycStatus: 'expired' });
    await notify(k.userId, { category: 'security', titleKey: 'n.kyc.expired.title', bodyKey: 'n.kyc.expired.body', params: {}, link: '/kyc', priority: 'high' });
  }
  return verified.length;
}

