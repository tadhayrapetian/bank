export async function payTax(id: string, fromAccountId: string) {
  const t = await db.taxes.get(id);
  if (!t) throw new BankError('NOT_FOUND');
  if (t.ownerId !== actor().userId && !actor().system) throw new BankError('PERMISSION_DENIED');
  if (t.status !== 'due' && t.status !== 'assessed') throw new BankError('INVALID_STATE', { status: t.status });
  const acc = await getAccountOrThrow(fromAccountId);
  if (!canOperate(acc)) throw new BankError('PERMISSION_DENIED');
  const owner = await db.users.get(t.ownerId);
  const tx = await execute({
    draft: {
      type: 'tax', amount: t.amount, currency: t.currency, fromAccountId: acc.id, sender: { name: owner?.name ?? 'Client', accountNumber: acc.number },
      recipient: { name: 'Revenue Office of Aldermoor' }, description: `${t.description} (${t.number})`, category: 'taxes', channel: 'app', refPrefix: 'TAX', meta: { taxId: t.id },
    },
    validate: async () => {
      const avail = await availableOf(acc.id, t.currency);
      if (avail < t.amount) throw new BankError('INSUFFICIENT_FUNDS', { available: avail, required: t.amount, currency: t.currency });
    },
    screen: false,
    plan: () => [{ memo: `Tax ${t.number}`, lines: [{ accountId: acc.id, currency: t.currency, side: 'D', amount: t.amount }, { accountId: GL.TAX, currency: t.currency, side: 'C', amount: t.amount }] }],
  });
  const doc = await createDocument({
    type: 'tax', title: 'Tax Payment Receipt', ownerId: t.ownerId, data: { taxId: t.id, number: t.number, kind: t.kind, year: t.year, amount: t.amount, currency: t.currency, description: t.description, paidAt: nowISO(), txId: tx.id, payer: owner?.name },
    links: { txIds: [tx.id], accountIds: [acc.id] }, authorName: 'Revenue Office of Aldermoor', authorId: 'BANK', silent: true,
  });
  await db.taxes.update(id, { status: 'paid', paidAt: nowISO(), txId: tx.id, documentId: doc.id });
  return tx;
}

export async function generateTaxStatement(year: number) {
  const a = actor();
  const records = await db.taxes.where('ownerId').equals(a.userId).filter((t) => t.year === year).toArray();
  const owner = await db.users.get(a.userId);
  const interestTx = await db.transactions.where('partyIds').equals(a.userId).filter((t) => (t.type === 'deposit_interest' || t.type === 'dividend') && t.createdAt.startsWith(String(year))).toArray();
  return createDocument({
    type: 'tax', title: `Annual Tax Statement ${year}`, ownerId: a.userId,
    data: { kind: 'annual', year, taxpayer: owner?.name, clientId: owner?.clientId, records: records.map((r) => ({ number: r.number, kind: r.kind, amount: r.amount, currency: r.currency, status: r.status })), income: interestTx.map((t) => ({ ref: t.ref, type: t.type, amount: t.amount, currency: t.currency, at: t.createdAt })) },
    body: ['This statement is generated by a simulation of the Revenue Office of Aldermoor for demonstration purposes only. It is not tax advice.'],
    authorName: 'Revenue Office of Aldermoor', authorId: 'BANK',
  });
}

export async function fileDeclaration(year: number, declaredIncome: number, currency: string) {
  const a = actor();
  if (!(declaredIncome >= 0)) throw new BankError('INVALID_AMOUNT');
  // Simulated flat rate for the fictional realm; not a real tax computation.
  const tax = Math.round(declaredIncome * 0.12);
  const rec: TaxRecord = {
    id: uid('TAXR'), number: `DCL-${year}-${randomDigits(5)}`, ownerId: a.userId, year, kind: 'declaration', amount: tax, currency, status: 'assessed',
    dueDate: `${year + 1}-04-15`, description: `Income declaration ${year} (simulated 12% flat assessment)`,
  };
  await db.taxes.add(rec);
  await audit({ action: 'tax.declare', object: 'tax', objectId: rec.id, details: `${declaredIncome} ${currency}` });
  await sendMail(a.userId, 'tax_notice', { number: rec.number, amt: tax, ccy: currency, due: rec.dueDate });
  return rec;
}

