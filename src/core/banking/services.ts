export async function rentVault(level: Vault['level'], size: Vault['size'], branchId: string, combination: string, accountId: string) {
  const a = actor();
  if (!/^\d{4,8}$/.test(combination)) throw new BankError('VALIDATION', { field: 'combination' });
  const acc = await getAccountOrThrow(accountId);
  if (!canOperate(acc)) throw new BankError('PERMISSION_DENIED');
  const fee = VAULT_LEVELS[level].fee * ({ S: 1, M: 1.5, L: 2.2, XL: 3.5 } as const)[size];
  const user = await db.users.get(acc.ownerId);
  await execute({
    draft: { type: 'vault', amount: Math.round(fee), currency: 'CRWN', fromAccountId: acc.id, sender: { name: user?.name ?? a.name, accountNumber: acc.number }, recipient: { name: 'Wardens of the Deep Vaults' }, description: `Vault rental (${VAULT_LEVELS[level].name}, ${size})`, category: 'bills', channel: 'app', refPrefix: 'VLT' },
    validate: async () => {
      const avail = await availableOf(acc.id, 'CRWN');
      if (avail < fee) throw new BankError('INSUFFICIENT_FUNDS', { available: avail, required: Math.round(fee), currency: 'CRWN' });
    },
    screen: false,
    plan: () => [{ memo: 'Vault rent', lines: [{ accountId: acc.id, currency: 'CRWN', side: 'D', amount: Math.round(fee) }, { accountId: GL.FEES, currency: 'CRWN', side: 'C', amount: Math.round(fee) }] }],
  });
  const salt = newSalt();
  const v: Vault = {
    id: uid('VLT'), number: `UV-${String(level)}${randomDigits(4)}`, ownerId: acc.ownerId, ownerName: user?.name ?? a.name, level, size, branchId, status: 'sealed',
    contents: [], rentFee: Math.round(fee), rentCurrency: 'CRWN', accountId: acc.id, combinationHash: await hashSecret(combination, salt), combinationSalt: salt,
    failedAttempts: 0, createdAt: nowISO(), wards: VAULT_LEVELS[level].wards,
  };
  await db.vaults.add(v);
  await logVault(v, 'rent', 'success', `${VAULT_LEVELS[level].name} ${size}`);
  return v;
}

export async function openVault(id: string, combination: string) {
  const v = await vaultFor(id);
  if (v.status === 'locked') throw new BankError('ACCOUNT_FROZEN', { vault: v.number });
  if (v.status === 'audit') throw new BankError('INVALID_STATE', { status: v.status });
  const ok = await verifySecret(combination, v.combinationSalt, v.combinationHash);
  if (!ok) {
    const attempts = v.failedAttempts + 1;
    await db.vaults.update(id, { failedAttempts: attempts, status: attempts >= 3 ? 'locked' : v.status });
    await logVault(v, 'failed_attempt', 'failure', `attempt ${attempts}`);
    if (attempts >= 3) {
      await notify(v.ownerId, { category: 'security', titleKey: 'n.vault.locked.title', bodyKey: 'n.vault.locked.body', params: { number: v.number }, link: `/vaults`, priority: 'high' });
      await sendMail(v.ownerId, 'vault_access', { number: v.number, event: 'locked' });
    }
    throw new BankError('VERIFICATION_FAILED', { attemptsLeft: Math.max(0, 3 - attempts) });
  }
  await db.vaults.update(id, { status: 'open', failedAttempts: 0 });
  await logVault(v, 'open', 'success');
  await notify(v.ownerId, { category: 'security', titleKey: 'n.vault.opened.title', bodyKey: 'n.vault.opened.body', params: { number: v.number }, link: '/vaults' });
}

export async function closeVault(id: string) {
  const v = await vaultFor(id);
  if (v.status !== 'open') throw new BankError('INVALID_STATE', { status: v.status });
  await db.vaults.update(id, { status: 'sealed' });
  await logVault(v, 'close', 'success');
}

export async function depositVaultItem(id: string, item: string, description: string, value?: number, currency?: string) {
  const v = await vaultFor(id);
  if (v.status !== 'open') throw new BankError('INVALID_STATE', { status: v.status });
  if (!item.trim()) throw new BankError('VALIDATION', { field: 'item' });
  await db.vaults.update(id, { contents: [...v.contents, { id: uid('VI', 6), item: item.trim(), description, value, currency, addedAt: nowISO() }] });
  await logVault(v, 'deposit_item', 'success', item);
}

export async function withdrawVaultItem(id: string, itemId: string) {
  const v = await vaultFor(id);
  if (v.status !== 'open') throw new BankError('INVALID_STATE', { status: v.status });
  const it = v.contents.find((c) => c.id === itemId);
  if (!it) throw new BankError('NOT_FOUND');
  await db.vaults.update(id, { contents: v.contents.filter((c) => c.id !== itemId) });
  await logVault(v, 'withdraw_item', 'success', it.item);
}

export async function unlockVault(id: string, newCombination?: string) {
  requirePermission('vaults.manage');
  const v = await vaultFor(id);
  const patch: Partial<Vault> = { status: 'sealed', failedAttempts: 0 };
  if (newCombination) {
    const salt = newSalt();
    patch.combinationHash = await hashSecret(newCombination, salt);
    patch.combinationSalt = salt;
  }
  await db.vaults.update(id, patch);
  await logVault(v, 'unlock', 'success');
}

export async function auditVault(id: string, start: boolean) {
  requirePermission('vaults.manage');
  const v = await vaultFor(id);
  await db.vaults.update(id, { status: start ? 'audit' : 'sealed' });
  await logVault(v, start ? 'audit' : 'close', 'success', start ? 'audit started' : 'audit finished');
}
